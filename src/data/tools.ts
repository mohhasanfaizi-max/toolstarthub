export function getToolBySlug(slug: string): Tool | undefined {
  return tools.find((tool) => tool.slug === slug);
}

export function getFeaturedTools(): Tool[] {
  return tools.filter((tool) => tool.featured);
}

export function getNewTools(): Tool[] {
  // The four most recently added tools (later entries are newer).
  return tools.filter((tool) => tool.new).slice(-4);
}

export function getToolsByCategory(category: CategorySlug): Tool[] {
  return tools.filter((tool) => tool.category === category);
}

export function getRelatedTools(tool: Tool, limit = 6): Tool[] {
  const selected = new Set<string>([tool.slug]);
  const related: Tool[] = [];

  for (const slug of tool.relatedSlugs ?? []) {
    const match = getToolBySlug(slug);
    if (match && !selected.has(match.slug)) {
      related.push(match);
      selected.add(match.slug);
    }
    if (related.length >= limit) {
      return related;
    }
  }

  const extras = tools.filter((item) => {
    if (selected.has(item.slug) || item.category !== tool.category) {
      return false;
    }
    return item.status === "available";
  });

  return [...related, ...extras].slice(0, limit);
}

export function searchTools(query: string): Tool[] {
  return rankTools(tools, query);
}

export function getToolSlugSet(): Set<string> {
  return new Set(tools.map((tool) => tool.slug));
}

export function getToolCategory(tool: Tool): Category | undefined {
  return categories.find((category) => category.slug === tool.category);
}
